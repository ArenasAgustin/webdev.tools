import { describe, it, expect, afterEach, vi } from "vitest";
import path from "node:path";

const root = path.resolve(__dirname, "../..");

type PluginLike = { name?: string } | PluginLike[] | false | null | undefined;

async function pluginNames(): Promise<string[]> {
  // A variable specifier keeps vite.config.ts out of the app's type-checked program.
  const specifier = path.join(root, "vite.config.ts");
  const mod = (await import(/* @vite-ignore */ specifier)) as {
    default: (env: { mode: string; command: string }) => { plugins?: PluginLike[] };
  };
  const plugins = mod.default({ mode: "production", command: "build" }).plugins ?? [];
  const flat = (plugins as unknown[]).flat(Infinity) as { name?: string }[];
  return flat.filter(Boolean).map((plugin) => plugin.name ?? "");
}

describe("bundle analyzer report (dist/stats.html)", () => {
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("is not generated by a normal build, so it is never deployed or precached", async () => {
    vi.stubEnv("ANALYZE", "");
    vi.stubEnv("npm_lifecycle_event", "build");
    expect(await pluginNames()).not.toContain("visualizer");
  });

  it("is generated when ANALYZE is set", async () => {
    vi.stubEnv("ANALYZE", "true");
    expect(await pluginNames()).toContain("visualizer");
  });
});
